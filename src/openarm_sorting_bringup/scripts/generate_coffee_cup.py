#!/usr/bin/env python3
"""Generate the `coffee_cup` Gazebo model used by the cup-sorting world.

Writes  src/openarm_sorting_bringup/models/coffee_cup/{model.config, model.sdf, meshes/*.obj}
(the SOURCE tree; rebuild the workspace afterwards to install the new files)

Visual  : smooth lathed ceramic mug body (rounded lip, foot ring, inner fillet)
          plus an elliptical handle, written as OBJ with per-vertex normals.
Collision: open-top cup built from primitives that DART handles robustly
          - one solid floor cylinder
          - N box segments forming the cylindrical wall (inner faces at INNER_R)
          - three boxes approximating the handle
The cup is static (it never moves), so no inertia tuning is required for it,
but a realistic inertial block is still provided.

Re-run after changing a dimension (from the workspace root):
    python3 src/openarm_sorting_bringup/scripts/generate_coffee_cup.py
If a dimension changes, update openarm_sorting_manipulation/config/cup_sorting_scene.yaml too.
"""
import math
import os

# ---------------- dimensions (metres) ----------------
INNER_R = 0.055       # 11.0 cm internal diameter
WALL = 0.005          # 5 mm ceramic wall
OUTER_R = INNER_R + WALL
HEIGHT = 0.095        # 9.5 cm tall (outer)
FLOOR = 0.008         # 8 mm thick bottom; inner floor at z = FLOOR
N_SEG = 96            # visual lathe resolution
N_WALL = 24           # collision wall segments
MASS = 0.45           # ceramic mug

HANDLE_ZC = 0.050     # handle vertical centre
HANDLE_AX = 0.030     # handle reach outward from the wall
HANDLE_AZ = 0.028     # handle half-height
HANDLE_TUBE = 0.0055  # handle tube radius

HERE = os.path.dirname(os.path.abspath(__file__))
MODEL_DIR = os.path.join(HERE, '..', 'models', 'coffee_cup')


def lathe_profile():
    """Closed (r, z) profile, traversed outer-bottom -> outer wall -> lip -> inner wall -> floor.
    Returns a list of polylines; each polyline gets its own vertex ring so corners stay crisp."""
    lip_c = ((INNER_R + OUTER_R) / 2, HEIGHT - WALL / 2)
    lip = [(lip_c[0] + (WALL / 2) * math.cos(a), lip_c[1] + (WALL / 2) * math.sin(a))
           for a in [i * math.pi / 12 for i in range(13)]]           # 0..180 deg, outer -> inner
    fillet = [(INNER_R - 0.004 + 0.004 * math.cos(a), FLOOR + 0.004 - 0.004 * math.sin(a))
              for a in [i * (math.pi / 2) / 6 for i in range(7)]]     # inner wall -> floor
    return [
        [(0.0, 0.002), (OUTER_R - 0.010, 0.002)],                    # recessed underside
        [(OUTER_R - 0.010, 0.002), (OUTER_R - 0.009, 0.0)],          # foot ring inner edge
        [(OUTER_R - 0.009, 0.0), (OUTER_R - 0.003, 0.0)],            # foot ring
        [(OUTER_R - 0.003, 0.0), (OUTER_R, 0.004)],                  # chamfer
        [(OUTER_R, 0.004), (OUTER_R, lip_c[1])],                     # outer wall
        lip,                                                          # rounded lip
        [(INNER_R, lip_c[1]), (INNER_R, FLOOR + 0.004)],             # inner wall
        fillet,                                                       # inner fillet
        [(INNER_R - 0.004, FLOOR), (0.0, FLOOR)],                    # inner floor
    ]


def write_obj(path, verts, normals, faces, name):
    with open(path, 'w') as f:
        f.write(f'# {name} - generated by generate_coffee_cup.py\no {name}\n')
        for v in verts:
            f.write('v %.6f %.6f %.6f\n' % v)
        for n in normals:
            f.write('vn %.6f %.6f %.6f\n' % n)
        for a, b, c in faces:
            f.write(f'f {a+1}//{a+1} {b+1}//{b+1} {c+1}//{c+1}\n')


def build_body():
    verts, normals, faces = [], [], []
    for poly in lathe_profile():
        # profile-space normals (outward = right-hand normal of the traversal direction)
        pn = []
        for i, (r, z) in enumerate(poly):
            a = poly[max(i - 1, 0)]
            b = poly[min(i + 1, len(poly) - 1)]
            dr, dz = b[0] - a[0], b[1] - a[1]
            L = math.hypot(dr, dz) or 1.0
            pn.append((dz / L, -dr / L))
        base = len(verts)
        for k in range(N_SEG + 1):
            th = 2 * math.pi * k / N_SEG
            c, s = math.cos(th), math.sin(th)
            for (r, z), (nr, nz) in zip(poly, pn):
                verts.append((r * c, r * s, z))
                normals.append((nr * c, nr * s, nz))
        m = len(poly)
        for k in range(N_SEG):
            for i in range(m - 1):
                p00 = base + k * m + i
                p01 = base + k * m + i + 1
                p10 = base + (k + 1) * m + i
                p11 = base + (k + 1) * m + i + 1
                faces.append((p00, p10, p11))
                faces.append((p00, p11, p01))
    return verts, normals, faces


def build_handle():
    verts, normals, faces = [], [], []
    nt, nc = 48, 16
    x0 = OUTER_R - 0.004                       # ends slightly embedded in the wall
    for i in range(nt + 1):
        t = -math.pi / 2 + math.pi * i / nt
        cx, cz = x0 + HANDLE_AX * math.cos(t), HANDLE_ZC + HANDLE_AZ * math.sin(t)
        tx, tz = -HANDLE_AX * math.sin(t), HANDLE_AZ * math.cos(t)   # tangent
        L = math.hypot(tx, tz); tx, tz = tx / L, tz / L
        nx, nz = tz, -tx                                              # in-plane normal
        for j in range(nc + 1):
            p = 2 * math.pi * j / nc
            # tube cross-section: in-plane normal and the y axis
            ox = nx * math.cos(p) * HANDLE_TUBE
            oz = nz * math.cos(p) * HANDLE_TUBE
            oy = math.sin(p) * HANDLE_TUBE * 0.8                      # slightly flattened
            verts.append((cx + ox, oy, cz + oz))
            n = (nx * math.cos(p), math.sin(p), nz * math.cos(p))
            L = math.sqrt(sum(v * v for v in n)); normals.append(tuple(v / L for v in n))
    for i in range(nt):
        for j in range(nc):
            a = i * (nc + 1) + j; b = a + 1; c = a + nc + 1; d = c + 1
            faces.append((a, c, d)); faces.append((a, d, b))
    return verts, normals, faces


def collision_sdf():
    out = []
    out.append(f'''      <collision name="floor">
        <pose>0 0 {FLOOR / 2:.4f} 0 0 0</pose>
        <geometry><cylinder><radius>{OUTER_R:.4f}</radius><length>{FLOOR:.4f}</length></cylinder></geometry>
        <surface><friction><ode><mu>0.8</mu><mu2>0.8</mu2></ode></friction></surface>
      </collision>''')
    rc = INNER_R + WALL / 2
    chord = 2 * rc * math.tan(math.pi / N_WALL) * 1.08          # small overlap between segments
    for k in range(N_WALL):
        th = 2 * math.pi * k / N_WALL
        out.append(f'''      <collision name="wall_{k:02d}">
        <pose>{rc * math.cos(th):.5f} {rc * math.sin(th):.5f} {HEIGHT / 2:.4f} 0 0 {th:.5f}</pose>
        <geometry><box><size>{WALL:.4f} {chord:.5f} {HEIGHT:.4f}</size></box></geometry>
        <surface><friction><ode><mu>0.8</mu><mu2>0.8</mu2></ode></friction></surface>
      </collision>''')
    # handle: outer bar + two short connectors
    hx = OUTER_R - 0.004 + HANDLE_AX
    out.append(f'''      <collision name="handle_outer">
        <pose>{hx:.4f} 0 {HANDLE_ZC:.4f} 0 0 0</pose>
        <geometry><box><size>{2 * HANDLE_TUBE:.4f} {1.6 * HANDLE_TUBE:.4f} {1.3 * HANDLE_AZ:.4f}</size></box></geometry>
      </collision>''')
    for sgn, nm in [(1, 'top'), (-1, 'bottom')]:
        out.append(f'''      <collision name="handle_{nm}">
        <pose>{OUTER_R + HANDLE_AX / 2 - 0.004:.4f} 0 {HANDLE_ZC + sgn * (HANDLE_AZ - HANDLE_TUBE):.4f} 0 0 0</pose>
        <geometry><box><size>{HANDLE_AX:.4f} {1.6 * HANDLE_TUBE:.4f} {2 * HANDLE_TUBE:.4f}</size></box></geometry>
      </collision>''')
    return '\n'.join(out)


def main():
    os.makedirs(os.path.join(MODEL_DIR, 'meshes'), exist_ok=True)
    write_obj(os.path.join(MODEL_DIR, 'meshes', 'cup_body.obj'), *build_body(), 'cup_body')
    write_obj(os.path.join(MODEL_DIR, 'meshes', 'cup_handle.obj'), *build_handle(), 'cup_handle')

    # inertia of a thin-walled open cylinder + disc (approximate)
    m_wall, m_floor = MASS * 0.8, MASS * 0.2
    ixx = m_wall * (OUTER_R ** 2 / 2 + HEIGHT ** 2 / 12) + m_floor * OUTER_R ** 2 / 4
    izz = m_wall * OUTER_R ** 2 + m_floor * OUTER_R ** 2 / 2

    material = '''<material>
          <ambient>0.92 0.91 0.88 1</ambient>
          <diffuse>0.94 0.93 0.90 1</diffuse>
          <specular>0.6 0.6 0.6 1</specular>
          <pbr><metal><metalness>0.0</metalness><roughness>0.18</roughness></metal></pbr>
        </material>'''
    sdf = f'''<?xml version="1.0"?>
<!-- Generated by openarm_sorting_bringup/scripts/generate_coffee_cup.py - edit the script, not this file. -->
<sdf version="1.9">
  <model name="coffee_cup">
    <static>true</static>
    <!-- Large ceramic coffee cup: internal diameter {2 * INNER_R * 100:.1f} cm,
         height {HEIGHT * 100:.1f} cm, inner floor at {FLOOR * 1000:.0f} mm, open top.
         Model origin = centre of the cup bottom. Handle points along model +x. -->
    <link name="cup_link">
      <inertial>
        <pose>0 0 {HEIGHT * 0.4:.4f} 0 0 0</pose>
        <mass>{MASS}</mass>
        <inertia><ixx>{ixx:.3e}</ixx><iyy>{ixx:.3e}</iyy><izz>{izz:.3e}</izz>
                 <ixy>0</ixy><ixz>0</ixz><iyz>0</iyz></inertia>
      </inertial>
      <visual name="body">
        <geometry><mesh><uri>model://coffee_cup/meshes/cup_body.obj</uri></mesh></geometry>
        {material}
      </visual>
      <visual name="handle">
        <geometry><mesh><uri>model://coffee_cup/meshes/cup_handle.obj</uri></mesh></geometry>
        {material}
      </visual>
{collision_sdf()}
    </link>
  </model>
</sdf>
'''
    with open(os.path.join(MODEL_DIR, 'model.sdf'), 'w') as f:
        f.write(sdf)
    with open(os.path.join(MODEL_DIR, 'model.config'), 'w') as f:
        f.write('''<?xml version="1.0"?>
<model>
  <name>coffee_cup</name>
  <version>1.0</version>
  <sdf version="1.9">model.sdf</sdf>
  <description>Large open-top ceramic coffee cup (11 cm inner diameter) used as the
  single destination for the OpenArm cup-sorting task. Generated by
  openarm_sorting_bringup/scripts/generate_coffee_cup.py.</description>
</model>
''')
    print('coffee_cup written to', os.path.normpath(MODEL_DIR))


if __name__ == '__main__':
    main()
